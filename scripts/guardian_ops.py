def cmd_programme(paths: GuardianPaths, args: argparse.Namespace) -> int:
    """
    Minimal "programme" placeholder: writes a short operational plan into CURRENT_STATE (non-destructive).
    """
    ensure_base_structure(paths)

    stamp = utc_now_iso()
    block = f"""

## Programme (auto)
- Generated: {stamp}
- Next steps:
  1) Update canonicals in `docs/` (single source-of-truth)
  2) Run: `guardian sync`, `guardian lint`, `guardian derive`
  3) Use `guardian next` to generate p0 from TODO scope
"""
    # Append if not already present
    existing = paths.current_state_file.read_text(encoding="utf-8", errors="replace")
    if "## Programme (auto)" in existing:
        print("OK: programme invariato (no-op).")
        return 0

    updated = existing.rstrip() + "\n" + block.lstrip()
    write_text_if_changed(paths.current_state_file, updated)
    print("DONE: programme scritto in CURRENT_STATE.md.")
    return 0


