def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig", errors="replace")


def extract_section(md: str, heading_regex: str) -> Optional[str]:
    """
    Very simple extractor: find a heading matching heading_regex and return until next same-or-higher heading.
    """
    # Normalize line endings
    md = md.replace("\r\n", "\n")
    lines = md.split("\n")

    # Find heading line index
    pattern = re.compile(heading_regex, re.IGNORECASE)
    start = None
    start_level = None

    for i, ln in enumerate(lines):
        m = re.match(r"^(#{1,6})\s+(.*)$", ln.strip())
        if not m:
            continue
        level = len(m.group(1))
        title = m.group(2).strip()
        if pattern.search(title):
            start = i
            start_level = level
            break

    if start is None or start_level is None:
        return None

    # Collect until next heading with level <= start_level
    out = [lines[start]]
    for j in range(start + 1, len(lines)):
        m = re.match(r"^(#{1,6})\s+.*$", lines[j].strip())
        if m and len(m.group(1)) <= start_level:
            break
        out.append(lines[j])

    return "\n".join(out).strip() + "\n"


def make_derived_header(title: str, sources: List[Path], paths: GuardianPaths, fingerprint: str) -> str:
    src_lines = "\n".join([f"- `{safe_rel(p, paths.repo_root)}`" for p in sources])
    return f"""# {title}

> GENERATED FILE — DO NOT EDIT  
> Source of truth: `./docs/`  
> Generated: {utc_now_iso()}  
> Fingerprint: {fingerprint}

## Sources
{src_lines}

---
"""


def derive_proj(paths: GuardianPaths, resolved_docs: List[Path], fingerprint: str) -> str:
    # Source docs
    ov = next((p for p in resolved_docs if p.name.startswith("001_")), None)
    pdr = next((p for p in resolved_docs if p.name.startswith("002_")), None)
    gaps = next((p for p in resolved_docs if p.name.startswith("009_")), None)

    sources = [p for p in [ov, pdr, gaps] if p is not None]
    header = make_derived_header("PROJ — Operational Project Brief", sources, paths, fingerprint)

    body = []
    if ov:
        ov_txt = read_text(ov)
        # Try extract a few useful sections; fallback to full summary block.
        for rx in [r"\bIn una frase\b", r"\bProblema\b", r"\bValore\b", r"\bPrincipi\b", r"\bUI\b", r"\bFasi\b"]:
            sec = extract_section(ov_txt, rx)
            if sec:
                body.append(sec)
        if not body:
            body.append("## Project Overview\n\n" + ov_txt.strip() + "\n")

    # Use-cases and acceptance from PDR
    if pdr:
        pdr_txt = read_text(pdr)
        sec = extract_section(pdr_txt, r"\bUse\s*Cases\b|\bCasi d'uso\b|\bUser\b|\bScenari\b")
        if sec:
            body.append(sec)
        sec2 = extract_section(pdr_txt, r"\bAcceptance\b|\bCriteri\b|\bDone\b|\bRequisiti\b")
        if sec2:
            body.append(sec2)

    # Gaps headline
    if gaps:
        gaps_txt = read_text(gaps)
        secg = extract_section(gaps_txt, r"\bGap\b|\bBacklog\b|\bManca\b")
        if secg:
            body.append(secg)

    # Operational UI mapping (lightweight template)
    body.append(
        """## UI — Operational Mapping (template)

Compila/raffina nei canonici di progetto (`docs/`) e rigenera con `guardian derive`.

| Pagina UI | A chi serve | Domanda tipica | Output |
|---|---|---|---|
| Decision Briefing | Retail | “Cosa faccio oggi?” | Lista segnali/ranking + disclosure |
| Gates & Data Quality | Retail/Dev | “I dati sono affidabili?” | Gate status + gaps |
| Audit Runs | Dev | “C’è look-ahead?” | Transcript + report |
| Forecast & Ranking | Retail | “Quali strumenti hanno miglior profilo?” | Stelle + confidence |
| NEWS-ALPHA | Retail | “Cosa muove il mercato?” | Sentiment + rating |
"""
    )

    return header + "\n\n".join(body).strip() + "\n"


def derive_tech(paths: GuardianPaths, resolved_docs: List[Path], fingerprint: str) -> str:
    pdd = next((p for p in resolved_docs if p.name.startswith("003_")), None)
    evidence = next((p for p in resolved_docs if p.name.startswith("008_")), None)
    trace = next((p for p in resolved_docs if p.name.startswith("005_")), None)

    sources = [p for p in [pdd, evidence, trace] if p is not None]
    header = make_derived_header("TECH — Operational Technical Brief", sources, paths, fingerprint)

    body = []

    if pdd:
        pdd_txt = read_text(pdd)
        for rx in [r"\bArchitettura\b|\bArchitecture\b", r"\bDataflow\b|\bPipeline\b", r"\bRunner\b|\bCLI\b", r"\bAudit\b|\bT\+1\b"]:
            sec = extract_section(pdd_txt, rx)
            if sec:
                body.append(sec)
        if not body:
            body.append("## PDD (full)\n\n" + pdd_txt.strip() + "\n")

    if evidence:
        ev_txt = read_text(evidence)
        se = extract_section(ev_txt, r"\bComandi\b|\bCommands\b|\bRunbook\b|\bOperativ")
        if se:
            body.append(se)

    # Inventory quick scan (scripts/pages) to keep doc aligned to repo shape
    scripts_dir = paths.repo_root / "scripts"
    pages_dir = paths.repo_root / "pages"
    src_dir = paths.repo_root / "src"

    def list_py(dir_path: Path, max_items: int = 50) -> List[str]:
        if not dir_path.exists():
            return []
        items = sorted([safe_rel(p, paths.repo_root) for p in dir_path.rglob("*.py") if p.is_file()])
        if len(items) > max_items:
            items = items[:max_items] + [f"... (+{len(items)-max_items} more)"]
        return items

    inv = []
    inv.append("## Repo Inventory (auto)\n")
    inv.append("### scripts/\n" + "\n".join([f"- `{x}`" for x in list_py(scripts_dir)]) + "\n")
    inv.append("### pages/\n" + "\n".join([f"- `{x}`" for x in list_py(pages_dir)]) + "\n")
    inv.append("### src/\n" + "\n".join([f"- `{x}`" for x in list_py(src_dir)]) + "\n")
    body.append("\n".join(inv))

    return header + "\n\n".join(body).strip() + "\n"


def derive_ddt(paths: GuardianPaths, resolved_docs: List[Path], fingerprint: str) -> str:
    ddt = next((p for p in resolved_docs if p.name.startswith("004_")), None)
    sources = [p for p in [ddt] if p is not None]
    header = make_derived_header("DDT — Operational Data Dictionary", sources, paths, fingerprint)

    if not ddt:
        return header + "## Missing\n\n`004_DDT_DATADICTIONARY.md` not found in `docs/`.\n"

    txt = read_text(ddt)

    # Try to extract key sections if present; else include entire doc.
    parts = []
    for rx in [r"\bSchema\b|\bTabelle\b|\bTables\b", r"\bColonne\b|\bColumns\b", r"\bVincoli\b|\bConstraints\b", r"\bSemantica\b|\bSemantics\b", r"\bTimezone\b|\bAs-of\b|\bGranular"]:
        sec = extract_section(txt, rx)
        if sec:
            parts.append(sec)

    if not parts:
        parts.append(txt.strip())

    # Add practical queries section (retail-friendly but engineering-grade)
    parts.append(
        """## Practical DuckDB Queries (template)

> Aggiorna nei canonici di progetto e rigenera con `guardian derive`.

- Elenco tabelle:
  - `SHOW TABLES;`
- Schema tabella:
  - `DESCRIBE <table_name>;`
- Conteggio righe e range date:
  - `SELECT MIN(date), MAX(date), COUNT(*) FROM <table>;`
"""
    )

    return header + "\n\n".join(parts).strip() + "\n"


def write_derived(paths: GuardianPaths, resolved_docs: List[Path], fingerprint: str) -> Tuple[int, int]:
    """
    Generate derived library files.
    Returns (written_count, no_op_count)
    """
    paths.derived_dir.mkdir(parents=True, exist_ok=True)

    outputs = [
        (paths.derived_dir / "PROJ.md", derive_proj(paths, resolved_docs, fingerprint)),
        (paths.derived_dir / "TECH.md", derive_tech(paths, resolved_docs, fingerprint)),
        (paths.derived_dir / "DDT.md", derive_ddt(paths, resolved_docs, fingerprint)),
    ]

    written = 0
    noop = 0
    for p, content in outputs:
        if write_text_if_changed(p, content):
            written += 1
        else:
            noop += 1
    return written, noop


