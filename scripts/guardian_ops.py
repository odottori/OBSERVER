def ensure_base_structure(paths: GuardianPaths) -> None:
    # Create directories
    paths.doc_root.mkdir(parents=True, exist_ok=True)
    paths.canonical_dir.mkdir(parents=True, exist_ok=True)
    paths.derived_dir.mkdir(parents=True, exist_ok=True)
    paths.guardian_dir.mkdir(parents=True, exist_ok=True)

    # Operational folders (logs live under .doc/ to keep repo root clean)
    logs_dir = paths.doc_root / "ops" / "logs"
    logs_dir.mkdir(parents=True, exist_ok=True)
    gi = logs_dir / ".gitignore"
    if not gi.exists():
        # Keep encoding plain utf-8 (no BOM) for gitignore
        write_text_if_changed(
            gi,
            "# Auto-generated: ignore operational logs\n*.log\n*.txt\n",
            encoding="utf-8",
        )

    # Templates folder (safe to update; used as reference for new repos)
    templates_dir = paths.guardian_dir / "templates"
    templates_dir.mkdir(parents=True, exist_ok=True)
    write_text_if_changed(templates_dir / "TODO_TEMPLATE.md", TODO_TEMPLATE)
    write_text_if_changed(templates_dir / "CURRENT_STATE_TEMPLATE.md", CURRENT_STATE_TEMPLATE)
    write_text_if_changed(templates_dir / "LOGBOOK_TEMPLATE.md", LOGBOOK_TEMPLATE)
    write_text_if_changed(templates_dir / "README_TEMPLATE.md", README_TEMPLATE)

    # Operational files (STRICT non-destructive)
    if not paths.readme_file.exists():
        write_text_if_changed(paths.readme_file, README_TEMPLATE)
    if not paths.todo_file.exists():
        write_text_if_changed(paths.todo_file, TODO_TEMPLATE)
    if not paths.current_state_file.exists():
        write_text_if_changed(paths.current_state_file, CURRENT_STATE_TEMPLATE.format(updated=utc_now_iso()))
    if not paths.logbook_file.exists():
        write_text_if_changed(paths.logbook_file, LOGBOOK_TEMPLATE.format(date=datetime.now().date().isoformat()))

    # Ensure index exists (non-destructive)
    if not paths.index_file.exists():
        write_text_if_changed(paths.index_file, CANONICAL_LIBRARY_HEADER)


