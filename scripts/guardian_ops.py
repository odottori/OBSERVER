def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="guardian_ops.py", add_help=True)
    sub = p.add_subparsers(dest="cmd", required=True)

    sub.add_parser("init", help="Initialize .doc/ scaffolding (non-destructive).")

    sp_sync = sub.add_parser("sync", help="Validate docs/ and update .doc/CANONICAL_LIBRARY.md (no copy).")
    sp_sync.add_argument("--clean", action="store_true", help="Remove legacy mirror folder .doc/canonical/project if present.")

    sub.add_parser("lint", help="Check structure and required docs; warns on legacy mirror.")
    sub.add_parser("derive", help="Generate derived operational library (.doc/canonical/derived/*).")
    sub.add_parser("status", help="Show current status summary.")
    sub.add_parser("programme", help="Write a small operational plan into CURRENT_STATE.md (optional).")

    return p


def main(argv: List[str]) -> int:
    paths = default_paths()
    parser = build_parser()
    args = parser.parse_args(argv)

    cmd = args.cmd
    if cmd == "init":
        return cmd_init(paths, args)
    if cmd == "sync":
        return cmd_sync(paths, args)
    if cmd == "lint":
        return cmd_lint(paths, args)
    if cmd == "derive":
        return cmd_derive(paths, args)
    if cmd == "status":
        return cmd_status(paths, args)
    if cmd == "programme":
        return cmd_programme(paths, args)

    print(f"ERROR: Unknown command: {cmd}")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
