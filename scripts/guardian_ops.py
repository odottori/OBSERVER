def utc_now_iso() -> str:
    return datetime.utcnow().replace(microsecond=0).isoformat() + "Z"


def sha256_bytes(data: bytes) -> str:
    h = hashlib.sha256()
    h.update(data)
    return h.hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def write_text_if_changed(path: Path, content: str, encoding: str = "utf-8-sig") -> bool:
    """
    Anti-churn: write only if content differs.
    Returns True if file written/updated, False if no-op.
    """
    # NOTE (EOL determinism): on Windows, text-mode writes translate "\n" -> "\r\n".
    # To avoid CRLF/LF churn and Git warnings, we treat the *desired* file bytes as the
    # source of truth and write with newline="\n".
    desired_bytes = content.encode(encoding)

    if path.exists():
        try:
            existing_bytes = path.read_bytes()
            if existing_bytes == desired_bytes:
                return False
        except Exception:
            # If unreadable, overwrite (rare)
            pass
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding=encoding, newline="\n") as f:
        f.write(content)
    return True


def safe_rel(p: Path, base: Path) -> str:
    try:
        return str(p.relative_to(base)).replace("\\", "/")
    except Exception:
        return str(p).replace("\\", "/")


def find_doc(docs_dir: Path, preferred: str, legacy_globs: List[str]) -> Optional[Path]:
    """
    Resolve canonical doc path in ./docs:
      1) preferred exact filename
      2) legacy globs (deterministic: sort)
    """
    pref = docs_dir / preferred
    if pref.exists():
        return pref

    matches: List[Path] = []
    for g in legacy_globs:
        matches.extend(sorted(docs_dir.glob(g)))

    # Deterministic selection: lexicographically last is often highest version;
    # but since we are moving towards versionless naming, pick last as best-effort.
    if matches:
        return matches[-1]

    return None


def collect_project_docs(paths: GuardianPaths) -> Tuple[List[Path], List[str]]:
    """
    Returns (resolved_required_docs, missing_doc_messages)
    """
    resolved: List[Path] = []
    missing: List[str] = []

    if not paths.docs_dir.exists():
        missing.append(f"Missing docs directory: {paths.docs_dir}")
        return ([], missing)

    for doc_id, human, preferred, legacy in REQUIRED_DOCS:
        p = find_doc(paths.docs_dir, preferred, legacy)
        if p is None:
            missing.append(f"[{doc_id}] Missing required doc: {preferred} (or legacy patterns: {legacy})")
        else:
            resolved.append(p)

    return resolved, missing


def compute_fingerprint(files: Iterable[Path], base: Path) -> str:
    """
    Deterministic fingerprint over relative paths + file hashes.
    """
    items: List[Tuple[str, str]] = []
    for f in files:
        if f.is_file():
            items.append((safe_rel(f, base), sha256_file(f)))
    items.sort(key=lambda x: x[0])

    blob = json.dumps(items, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return sha256_bytes(blob)[:16]  # short fingerprint for readability


