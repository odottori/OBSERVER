def build_canonical_library(paths: GuardianPaths, project_docs: List[Path], fingerprint: str) -> str:
    lines = [CANONICAL_LIBRARY_HEADER]
    lines.append(f"- Updated: {utc_now_iso()}")
    lines.append(f"- Mode: **single source-of-truth** (`docs/`), no mirror copies in `.doc/`")
    lines.append(f"- Project docs fingerprint: `{fingerprint}`")
    lines.append("")
    lines.append("## Project canonicals (source of truth)")
    for p in project_docs:
        lines.append(f"- `{safe_rel(p, paths.repo_root)}`  (sha256: `{sha256_file(p)[:16]}`)")
    lines.append("")
    lines.append("## Derived operational library (generated)")
    if paths.derived_dir.exists():
        derived_files = sorted([p for p in paths.derived_dir.glob("*.md") if p.is_file()])
        if derived_files:
            for p in derived_files:
                lines.append(f"- `{safe_rel(p, paths.repo_root)}`  (sha256: `{sha256_file(p)[:16]}`)")
        else:
            lines.append("- (none yet) run `guardian derive`")
    else:
        lines.append("- (missing derived dir) run `guardian init`")
    lines.append("")
    lines.append("## Notes")
    lines.append("- Edit canonicals only in `docs/`.")
    lines.append("- Do not edit anything under `.doc/canonical/**` manually.")
    lines.append("")
    return "\n".join(lines).strip() + "\n"


