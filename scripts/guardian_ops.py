def cmd_init(paths: GuardianPaths, args: argparse.Namespace) -> int:
    ensure_base_structure(paths)
    print("DONE: init completato (template .doc/ presenti).")
    return 0


def cmd_sync(paths: GuardianPaths, args: argparse.Namespace) -> int:
    ensure_base_structure(paths)

    # Optional cleanup of legacy mirror folder
    legacy_mirror = paths.canonical_dir / "project"
    if args.clean and legacy_mirror.exists():
        shutil.rmtree(legacy_mirror)
        print(f"INFO: removed legacy mirror folder: {safe_rel(legacy_mirror, paths.repo_root)}")

    project_docs, missing = collect_project_docs(paths)
    if missing:
        for m in missing:
            print(f"ERROR: {m}")
        return 2

    fingerprint = compute_fingerprint(project_docs, paths.repo_root)
    idx = build_canonical_library(paths, project_docs, fingerprint)
    changed = write_text_if_changed(paths.index_file, idx)

    print(f"DONE: sync completato. mode=direct, docs={len(project_docs)}, index_updated={1 if changed else 0}, fingerprint={fingerprint}…")
    return 0


def cmd_lint(paths: GuardianPaths, args: argparse.Namespace) -> int:
    ensure_base_structure(paths)

    errors: List[str] = []
    warnings: List[str] = []

    # Structure checks
    if not paths.docs_dir.exists():
        errors.append(f"Missing required directory: {safe_rel(paths.docs_dir, paths.repo_root)}")

    # Disallow mirror folder (confusion source)
    legacy_mirror = paths.canonical_dir / "project"
    if legacy_mirror.exists():
        warnings.append(
            f"Legacy mirror folder exists: {safe_rel(legacy_mirror, paths.repo_root)}. "
            f"This setup uses direct mode; consider `guardian sync --clean`."
        )

    # Required docs checks
    project_docs, missing = collect_project_docs(paths)
    if missing:
        errors.extend(missing)

    # Derived allowlist checks
    allowed_derived = {"PROJ.md", "TECH.md", "DDT.md"}
    if paths.derived_dir.exists():
        for p in paths.derived_dir.glob("*.md"):
            if p.is_file() and p.name not in allowed_derived:
                warnings.append(f"Unexpected derived file: {safe_rel(p, paths.repo_root)} (allowed: {sorted(allowed_derived)})")

    # Basic index presence
    if not paths.index_file.exists():
        warnings.append(f"Missing index file: {safe_rel(paths.index_file, paths.repo_root)} (run `guardian sync`)")

    if errors:
        for e in errors:
            print(f"FAIL: {e}")
        for w in warnings:
            print(f"WARN: {w}")
        return 2

    for w in warnings:
        print(f"WARN: {w}")

    print("PASS: docs e canonici operativi risultano coerenti (direct mode).")
    return 0


def cmd_derive(paths: GuardianPaths, args: argparse.Namespace) -> int:
    ensure_base_structure(paths)

    project_docs, missing = collect_project_docs(paths)
    if missing:
        for m in missing:
            print(f"ERROR: {m}")
        return 2

    fingerprint = compute_fingerprint(project_docs, paths.repo_root)

    written, noop = write_derived(paths, project_docs, fingerprint)

    # Update index with derived listing (optional but useful)
    idx = build_canonical_library(paths, project_docs, fingerprint)
    write_text_if_changed(paths.index_file, idx)

    if written == 0:
        print("OK: derived library invariata (no-op).")
    else:
        print(f"DONE: derived library aggiornata. written={written}, no_op={noop}, fingerprint={fingerprint}…")
    return 0


def cmd_status(paths: GuardianPaths, args: argparse.Namespace) -> int:
    ensure_base_structure(paths)

    project_docs, missing = collect_project_docs(paths)
    if missing:
        print("STATUS: incomplete (missing required docs).")
        for m in missing:
            print(f"- {m}")
        return 1

    fingerprint = compute_fingerprint(project_docs, paths.repo_root)
    derived_files = sorted([p for p in paths.derived_dir.glob("*.md") if p.is_file()])

    print("STATUS: GUARDIAN OPS (direct mode)")
